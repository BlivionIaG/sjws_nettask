package sjws_nettask.routing;

import java.util.Objects;
import sjws_nettask.core.Handler;
import sjws_nettask.core.Problem;
import sjws_nettask.core.Request;
import sjws_nettask.core.Response;
import sjws_nettask.core.StaticFileHandler;

/**
 * Per-route wrapper ({@code errors: problem}): error pages generated by this server for the route
 * ({@link StaticFileHandler#isGenerated}) with a status {@link Problem#supports supported} are
 * re-rendered as RFC 9457 {@code application/problem+json}. Other statuses keep the HTML page, and
 * responses relayed from an upstream are never touched. Only built when a route opts in, so routes
 * without it pay nothing.
 * <p>
 * The route's prefix rewrite is applied here (the {@code Route} gets none) so {@code instance}
 * is the path the client asked for, not the rewritten one.
 */
public final class ProblemErrorHandler implements Handler {

    private final Handler inner;
    private final Router.Route rewrite;
    private final String typeBase;

    /**
     * @param rewrite replacement for {@code prefix}, or null
     * @param typeBase see {@link Problem#of}; null for "about:blank"
     */
    public ProblemErrorHandler(Handler inner, String prefix, String rewrite, String typeBase) {
        this.inner = Objects.requireNonNull(inner, "inner");
        this.rewrite = rewrite == null ? null : new Router.Route(null, prefix, rewrite, inner);
        this.typeBase = typeBase;
    }

    @Override
    public Response handle(Request request) {
        var target = request.target();
        var response = this.inner.handle(this.rewrite == null ? request
                : request.withTarget(this.rewrite.rewriteTarget(target)));
        int status = response.status();
        if (status < 400 || !Problem.supports(status) || !StaticFileHandler.isGenerated(response)) {
            return response;
        }
        int q = target.indexOf('?');
        var instance = target.startsWith("/") ? (q < 0 ? target : target.substring(0, q)) : null;
        return Problem.of(status, this.typeBase, instance, response.headers(), response.headOnly());
    }
}
